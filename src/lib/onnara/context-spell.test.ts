import { describe, expect, it } from 'vitest';
import { applyContextFixes, findContextFixes } from './context-spell';

describe('applyContextFixes — 문맥 혼동어', () => {
  it.each([
    ['정부입법정책수행의 효율성 재고 등에 관한 규정', '정부입법정책수행의 효율성 제고 등에 관한 규정'],
    ['업무 효율성을 재고하기 위하여', '업무 효율성을 제고하기 위하여'],
    ['청렴도 재고 방안', '청렴도 제고 방안'],
    ['물품 제고 관리 철저', '물품 재고 관리 철저'],
    ['부서장 결제를 받아', '부서장 결재를 받아'],
    ['결제권자 확인 후', '결재권자 확인 후'],
    ['카드 결재 시', '카드 결제 시'],
    ['담당자로써 책임을 다하고', '담당자로서 책임을 다하고'],
    ['공무원으로써의 자세', '공무원으로서의 자세'],
    ['대화를 수단으로서', '대화를 수단으로써'],
    ['외부 반출을 일체 금지함', '외부 반출을 일절 금지함'],
    ['과태료를 부가할 수 있다', '과태료를 부과할 수 있다'],
    ['조례 재정 및 개정', '조례 제정 및 개정'],
    ['의견을 재출하여 주시기 바랍니다', '의견을 제출하여 주시기 바랍니다'],
    ['개선 방안을 재시하고', '개선 방안을 제시하고'],
    ['자료를 재공하여', '자료를 제공하여'],
    ['홈페이지에 개제할 예정', '홈페이지에 게재할 예정'],
    ['몇일간 소요', '며칠간 소요'],
    ['금새 처리됬음', '금세 처리됐음'],
    ['교육 참여률 향상', '교육 참여율 향상'],
    ['사업 집행율 점검', '사업 집행률 점검'],
  ])('%s → %s', (input, expected) => {
    expect(applyContextFixes(input)).toBe(expected);
  });

  it.each([
    '재고 관리 현황을 파악',
    '원안을 재고하여 주시기 바랍니다',
    '전자결제 시스템 도입',
    '자료 일체를 제출',
    '부가가치세 신고',
    '지방 재정 여건',
    '몇 일자리를 만들었나',
    '법률 개정, 확률, 비율, 합격률, 할인율, 성장률, 환율',
    '결재를 받아 시행',
    '효율성 제고',
  ])('바꾸지 않음: %s', (input) => {
    expect(applyContextFixes(input)).toBe(input);
  });

  it('멱등: 고친 글에 다시 적용해도 같다', () => {
    const once = applyContextFixes('효율성 재고, 부서장 결제, 참여률');
    expect(applyContextFixes(once)).toBe(once);
  });

  it('위치와 이유를 함께 돌려준다', () => {
    const [fix] = findContextFixes('효율성 재고 등');
    expect(fix).toMatchObject({ ruleId: 'jego', index: 4, from: '재고', to: '제고' });
    expect(fix!.reason).toContain('제고');
  });
});
