const RCON = new Uint8Array([0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36]);

function gmul(a: number, b: number): number {
  let p = 0;
  for (let i = 0; i < 8; i++) {
    if (b & 1) p ^= a;
    const hi = a & 0x80;
    a = (a << 1) & 0xff;
    if (hi) a ^= 0x1b;
    b >>= 1;
  }
  return p;
}

function expandKey(key: Uint8Array): Uint32Array {
  const w = new Uint32Array(44);
  for (let i = 0; i < 4; i++) {
    w[i] = ((key[4 * i]! << 24) | (key[4 * i + 1]! << 16) | (key[4 * i + 2]! << 8) | key[4 * i + 3]!) >>> 0;
  }
  for (let i = 4; i < 44; i++) {
    let t = w[i - 1]!;
    if (i % 4 === 0) {
      t = ((t << 8) | (t >>> 24)) >>> 0;
      t = ((S_BOX[(t >>> 24) & 0xff]! << 24) | (S_BOX[(t >>> 16) & 0xff]! << 16) | (S_BOX[(t >>> 8) & 0xff]! << 8) | S_BOX[t & 0xff]!) >>> 0;
      t = (t ^ (RCON[i / 4 - 1]! << 24)) >>> 0;
    }
    w[i] = (w[i - 4]! ^ t) >>> 0;
  }
  return w;
}

function addRoundKey(s: Uint8Array, w: Uint32Array, round: number): void {
  const base = round * 4;
  for (let c = 0; c < 4; c++) {
    const k = w[base + c]!;
    s[c * 4]! ^= (k >>> 24) & 0xff;
    s[c * 4 + 1]! ^= (k >>> 16) & 0xff;
    s[c * 4 + 2]! ^= (k >>> 8) & 0xff;
    s[c * 4 + 3]! ^= k & 0xff;
  }
}

function decryptBlock(block: Uint8Array, w: Uint32Array): Uint8Array {
  const s = new Uint8Array(16);
  s.set(block);
  addRoundKey(s, w, 10);
  for (let r = 9; r >= 1; r--) {
    let t = s[13]!; s[13] = s[9]!; s[9] = s[5]!; s[5] = s[1]!; s[1] = t;
    t = s[2]!; s[2] = s[10]!; s[10] = t;
    t = s[6]!; s[6] = s[14]!; s[14] = t;
    t = s[3]!; s[3] = s[7]!; s[7] = s[11]!; s[11] = s[15]!; s[15] = t;
    for (let i = 0; i < 16; i++) s[i] = INV_S_BOX[s[i]!]!;
    addRoundKey(s, w, r);
    for (let c = 0; c < 4; c++) {
      const i = c * 4;
      const a0 = s[i]!, a1 = s[i + 1]!, a2 = s[i + 2]!, a3 = s[i + 3]!;
      s[i] = gmul(a0, 0x0e) ^ gmul(a1, 0x0b) ^ gmul(a2, 0x0d) ^ gmul(a3, 0x09);
      s[i + 1] = gmul(a0, 0x09) ^ gmul(a1, 0x0e) ^ gmul(a2, 0x0b) ^ gmul(a3, 0x0d);
      s[i + 2] = gmul(a0, 0x0d) ^ gmul(a1, 0x09) ^ gmul(a2, 0x0e) ^ gmul(a3, 0x0b);
      s[i + 3] = gmul(a0, 0x0b) ^ gmul(a1, 0x0d) ^ gmul(a2, 0x09) ^ gmul(a3, 0x0e);
    }
  }
  let t = s[13]!; s[13] = s[9]!; s[9] = s[5]!; s[5] = s[1]!; s[1] = t;
  t = s[2]!; s[2] = s[10]!; s[10] = t;
  t = s[6]!; s[6] = s[14]!; s[14] = t;
  t = s[3]!; s[3] = s[7]!; s[7] = s[11]!; s[11] = s[15]!; s[15] = t;
  for (let i = 0; i < 16; i++) s[i] = INV_S_BOX[s[i]!]!;
  addRoundKey(s, w, 0);
  return s;
}

export function aes128EcbDecrypt(data: Uint8Array, key: Uint8Array): Uint8Array {
  const w = expandKey(key);
  const out = new Uint8Array(data.byteLength);
  for (let off = 0; off + 16 <= data.byteLength; off += 16) {
    out.set(decryptBlock(data.subarray(off, off + 16), w), off);
  }
  return out;
}

/** HWP 압축 스트림 해제(zlib 헤더 우선, 실패 시 raw deflate). */
export function decompressHwpStream(data: Uint8Array): Uint8Array {
  let out: Uint8Array;
  if (data.byteLength >= 2 && data[0] === 0x78) {
    try {
      out = unzlibSync(data);
    } catch {
      out = inflateSync(data);
    }
  } else {
    out = inflateSync(data);
  }
  if (out.byteLength > MAX_DECOMPRESS_BYTES) {
    throw new Error('압축 해제 크기가 상한을 초과했습니다.');
  }
  return out;
}

/** 배포용 HWP ViewText/Section{N} 복호화 (+ 압축 해제). */
export function decryptDistributionSection(raw: Uint8Array, compressed: boolean): Uint8Array {
  if (raw.byteLength < 260) throw new Error('배포용 섹션 데이터가 너무 짧습니다.');
  const view = new DataView(raw.buffer, raw.byteOffset, raw.byteLength);
  const hdr = view.getUint32(0, true);
  const tagId = hdr & 0x3ff;
  let size = (hdr >>> 20) & 0xfff;
  let hdrSize = 4;
  if (size === 0xfff) {
    size = view.getUint32(4, true);
    hdrSize = 8;
  }
  if (tagId !== TAG_DISTRIBUTE_DOC_DATA || size < 256 || hdrSize + size > raw.byteLength) {
    throw new Error('배포용 문서 헤더 레코드가 올바르지 않습니다.');
  }

  // MSVC LCG + XOR로 256B payload 복호화
  const payload = new Uint8Array(raw.subarray(hdrSize, hdrSize + 256));
  let seed = (payload[0]! | (payload[1]! << 8) | (payload[2]! << 16) | (payload[3]! << 24)) >>> 0;
  const rand = () => {
    seed = (Math.imul(seed, 214013) + 2531011) >>> 0;
    return (seed >>> 16) & 0x7fff;
  };
  let n = 0;
  let keyByte = 0;
  for (let i = 0; i < 256; i++) {
    if (n === 0) {
      keyByte = rand() & 0xff;
      n = (rand() & 0x0f) + 1;
    }
    if (i >= 4) payload[i]! ^= keyByte;
    n--;
  }

  const keyOffset = 4 + (payload[0]! & 0x0f);
  const aesKey = payload.subarray(keyOffset, keyOffset + 16);
  const enc = raw.subarray(hdrSize + size);
  const alignedLen = enc.byteLength - (enc.byteLength % 16);
  if (alignedLen <= 0) throw new Error('배포용 암호화 본문이 비어 있습니다.');

  const decrypted = aes128EcbDecrypt(enc.subarray(0, alignedLen), aesKey);
  if (!compressed) return decrypted;
  try {
    return decompressHwpStream(decrypted);
  } catch {
    return decrypted;
  }
}
